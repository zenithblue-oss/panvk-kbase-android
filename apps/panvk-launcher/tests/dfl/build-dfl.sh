#!/bin/sh
# Build the PanPlay D3D feature-level tests d3d12fl-<arch>.exe and d3d11fl-<arch>.exe (PanVK project code, MIT).
# Shaders: dfl.hlsl (SM5) and dfl4.hlsl (SM4.x) -> DXBC with vkd3d-compiler 1.19 (../dx12/scripts/build-vkd3d-compiler.sh)
# -> dfl_shaders.h (xxd -i, checked in, so the exes build without the compiler: DFL_SKIP_SHADERS=1).
# usage: build-dfl.sh <out dir> [x86_64|arm64ec|i686|aarch64 ...]   (default x86_64 arm64ec)
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
OUT=$1
shift
ARCHES=${*:-x86_64 arm64ec}
MINGW=${MINGW:-/home/flux/build-cache/dx12-test/toolchain/llvm-mingw-20260922-ucrt-ubuntu-22.04-aarch64}
VKC=${VKD3D_COMPILER:-/home/flux/build-cache/dx12-test/tools-build/vkd3d-compiler/vkd3d-compiler}
export SOURCE_DATE_EPOCH=${SOURCE_DATE_EPOCH:-1}
mkdir -p "$OUT"
if [ -z "${DFL_SKIP_SHADERS:-}" ]; then
    T=$(mktemp -d)
    trap 'rm -rf "$T"' EXIT
    cd "$HERE"
    # entry:profile:source:array name
    for e in vs_full:vs_5_0 vs_cb:vs_5_0 vs_spin:vs_5_0 vs_uav:vs_5_0 vs_inst:vs_5_0 vs_ctl:vs_5_0 hs_main:hs_5_0 \
             ds_bulge:ds_5_0 gs_quad:gs_5_0 ps_green:ps_5_0 ps_vcol:ps_5_0 ps_mrt:ps_5_0 ps_uint:ps_5_0 \
             ps_count:ps_5_0 ps_rov:ps_5_0 cs_write:cs_5_0 cs_typed:cs_5_0 cs_bind:cs_5_0 cs_tiled:cs_5_0; do
        "$VKC" -p "${e#*:}" -e "${e%%:*}" -b dxbc-tpf dfl.hlsl -o "$T/${e%%:*}.dxbc"
    done
    for e in vs_full:vs_4_0:4 vs_cb:vs_4_0:4 vs_spin:vs_4_0:4 gs_quad:gs_4_0:4 ps_green:ps_4_0:4 ps_vcol:ps_4_0:4 \
             ps_cubearr:ps_4_1:41 ps_gather:ps_4_1:41; do
        n=${e%%:*}; r=${e#*:}; p=${r%%:*}; s=${r#*:}
        "$VKC" -p "$p" -e "$n" -b dxbc-tpf dfl4.hlsl -o "$T/${n}_$s.dxbc"
    done
    {
        echo "/* Generated by build-dfl.sh from dfl.hlsl and dfl4.hlsl (vkd3d-compiler 1.19, dxbc-tpf). Do not edit."
        echo " * <entry>_dxbc: shader model 5.0; <entry>_4_dxbc: 4.0; <entry>_41_dxbc: 4.1. */"
        for f in "$T"/*.dxbc; do
            (cd "$T" && xxd -i "$(basename "$f")")
        done | sed -e 's/^unsigned char /static const unsigned char /' -e '/_len = /d'
    } > "$HERE/dfl_shaders.h"
fi
for arch in $ARCHES; do
    CC=$MINGW/bin/$arch-w64-mingw32-clang
    for t in d3d12fl d3d11fl; do
        "$CC" -std=gnu11 -O2 -DNDEBUG -D_WIN32_WINNT=0x0A00 -DWINVER=0x0A00 -Wall -Wno-unused-const-variable \
            -Wno-unused-command-line-argument "$HERE/$t.c" -static -s -mconsole -Wl,--no-insert-timestamp \
            -o "$OUT/$t-$arch.exe" -ld3d12 -ld3d11 -ldxgi -luser32 -lgdi32 -lm
        echo "built $OUT/$t-$arch.exe"
    done
done
